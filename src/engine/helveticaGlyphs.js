/**
 * Returns the kerning value between two characters in pixels.
 * Uses the live opentype font object if available, otherwise looks up HELVETICA_KERN_TABLE.
 */
export function getHelveticaKerning(charA, charB, font = null) {
  if (!charA || !charB) return 0;
  if (font) {
    const gA = font.charToGlyph(charA);
    const gB = font.charToGlyph(charB);
    if (gA && gB) {
      const val = font.getKerningValue(gA, gB);
      if (val !== 0) {
        return (val / font.unitsPerEm) * FONT_SIZE;
      }
    }
  }
  const direct = HELVETICA_KERN_TABLE[charA + charB];
  if (typeof direct === 'number') return direct;
  return 0;
}

/**
 * Returns character typographic metrics (advance, lsb, rsb, width, d).
 */
export function getCharMetrics(ch, font = null) {
  if (font) {
    const g = font.charToGlyph(ch);
    const bbox = g.getBoundingBox();
    const scale = FONT_SIZE / font.unitsPerEm;
    const advance = +(g.advanceWidth * scale).toFixed(3);
    const lsb = +(bbox.x1 * scale).toFixed(3);
    const rsb = +((g.advanceWidth - bbox.x2) * scale).toFixed(3);
    const width = +((bbox.x2 - bbox.x1) * scale).toFixed(3);
    const d = g.getPath(0, 0, FONT_SIZE).toPathData(2);
    return { advance, lsb, rsb, minX: lsb, maxX: lsb + width, width, d };
  }
  const cached = HELVETICA_GLYPHS[ch];
  if (cached) return cached;
  // Fallback for unknown character
  return {
    advance: 20,
    lsb: 2,
    rsb: 2,
    minX: 2,
    maxX: 18,
    width: 16,
    d: ''
  };
}
